def test_a_pdf_with_its_own_text_layer_is_read_from_the_file_not_the_pixels(born_digital):
    """Recognising a page that already has perfect text is slow and worse.

    This is a regression test. The pipeline passes ``cfg.ocr.languages`` -
    Tesseract's codes, ``["eng"]`` - into the quality check, which measures the
    stopword ratio against ISO 639-1 lists (``"en"``). When those codes were
    passed through unmapped, no token matched any list, the ratio came back
    0.00 on flawless English prose, every page was judged garbage, and the
    whole collection was re-read by OCR: slower, worse text, and a text layer
    replaced for no reason.
    """
    collection, outcomes = born_digital
    assert len(outcomes) == 2
    for outcome in outcomes:
        page = outcome.page
        assert outcome.error is None
        assert page.source is TextSource.EMBEDDED, outcome.warnings
        assert page.quality.verdict is PageVerdict.GOOD, page.quality.reasons
        assert page.quality.stopword_ratio > 0.25, (
            "English prose scored like OCR garbage; the language codes did not "
            f"reach the stopword lists: {page.quality.reasons}"
        )
    assert collection.stats.ocr_pages == 0
    assert not [w for o in outcomes for w in o.warnings if "unusable" in w]


def test_the_words_read_from_the_file_are_the_words_on_the_page(born_digital):
    """A text layer that parses but says nothing is the failure this catches."""
