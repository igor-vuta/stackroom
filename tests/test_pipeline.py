def test_source_date_epoch_pins_the_one_thing_that_is_not_the_input(tmp_path, monkeypatch):
    """Guarantee 6 needs a build stamp that is a function of something.

    ``built_at`` is written into ``manifest.json`` and printed into the footer of
    every page, so without this two people who build the same folder on
    different days differ in every file and "same input bytes, same output
    bytes" is false as stated. ``SOURCE_DATE_EPOCH`` is the
    reproducible-builds convention for exactly this.
    """
    root = tmp_path / "papers"
    root.mkdir()
    synth.born_digital_pdf(root / "memo.pdf", pages=1)

    monkeypatch.setenv("SOURCE_DATE_EPOCH", "1717200000")
    first, _ = build_collection(root, fast_config(), tmp_path / "a", workers=1)
    second, _ = build_collection(root, fast_config(), tmp_path / "b", workers=1)
    assert first.build.built_at == second.build.built_at == "2024-06-01T00:00:00+00:00"

    # And the default is still the clock.
    monkeypatch.delenv("SOURCE_DATE_EPOCH")
    third, _ = build_collection(root, fast_config(), tmp_path / "c", workers=1)
    assert third.build.built_at != first.build.built_at


@pytest.mark.parametrize("value", ["", "  ", "not-a-number", "1717200000.5", "99999999999999999999"])
def test_an_unusable_source_date_epoch_is_not_silently_believed(value, monkeypatch):
    """A malformed value must not become a date, and the CLI refuses it.

    Falling back to the clock is the right thing for the library - a stray
    environment variable cannot be allowed to stop a build - but somebody who
    exported this asked for a stamp that does not move, so being quietly given
    the clock instead is the opposite of what they asked for. The CLI checks it
    up front and says so.
    """
    from stackroom import cli as cli_mod

    monkeypatch.setenv("SOURCE_DATE_EPOCH", value)
    assert model.source_date_epoch() is None
    assert model.build_timestamp()  # the clock, not a crash

    if value.strip():
        with pytest.raises(Exception) as refused:
            cli_mod._check_source_date_epoch()
        assert refused.type.__name__ == "Exit"
    else:
        cli_mod._check_source_date_epoch()  # unset is not an error


