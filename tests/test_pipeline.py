# --------------------------------------------------------------------------
# the near field is measured in the units it says it is
#
# `exemptions.associate` scales horizontal gaps by width/height and `Page.aspect`
# is height/width, so handing one straight to the other squares the page up the
# wrong way and shrinks the near field horizontally by 1.67x - 24pt where the
# docstring promises 40. It only ever drops a code, never invents one, which is
# why it survived so long. The geometry below is the gap it lost.
# --------------------------------------------------------------------------

LETTER_W, LETTER_H = 612.0, 792.0


def _letter_page(*, code_at: float) -> tuple[Page, Redaction]:
    """A Letter page with one box and one code *code_at* points to its right.

    The code sits on the line *below* the box - 8pt of clear vertical space -
    so `_shares_a_line` says no and the near field is the only thing left to
    decide it. Everything is well clear of the header and footer bands.
    """
    box = Box(100 / LETTER_W, 300 / LETTER_H, 100 / LETTER_W, 12 / LETTER_H)
    redaction_ = Redaction(box=box, kind=model.RedactionKind.VECTOR)
    stamp = Word(
        text="(b)(6)",
        box=Box((200 + code_at) / LETTER_W, 320 / LETTER_H, 50 / LETTER_W, 12 / LETTER_H),
        line=1,
    )
    page = Page(
        number=1,
        width_pt=LETTER_W,
        height_pt=LETTER_H,
        words=[stamp],
        redactions=[redaction_],
    )
    return page, redaction_


def _annotated_page(page: Page) -> None:
    annotate_document(
        Document(id="d", title="d", filename="d.pdf", sha256="0" * 64, size_bytes=1, pages=[page])
    )


def test_the_page_hands_the_association_rule_width_over_height():
    """0.773 on Letter, not 1.294. The two are a factor of 1.67 apart."""
    page = Page(number=1, width_pt=LETTER_W, height_pt=LETTER_H)
    assert page.aspect == pytest.approx(1.294, abs=0.001)
    assert _width_over_height(page) == pytest.approx(0.7727, abs=0.0001)
    assert _width_over_height(Page(number=1, width_pt=595.0, height_pt=842.0)) == pytest.approx(
        0.7067, abs=0.0001
    )


def test_a_page_with_no_height_falls_back_instead_of_dividing_by_zero():
    """`Page.aspect` makes the same fallback for a page with no width."""
    assert _width_over_height(Page(number=1, height_pt=0.0)) == pytest.approx(0.7727, abs=0.0001)


def test_a_code_30pt_across_the_page_is_inside_the_near_field():
    """Documented as 40pt on Letter. Under the inverted ratio it was 24."""
    page, redaction_ = _letter_page(code_at=30.0)
    _annotated_page(page)
