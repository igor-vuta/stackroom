def test_a_dense_page_counts_for_more_than_a_one_line_page():
    """Why the figure is an area and not a mean of per-page shares.

    Two pages: a full page of text with a tenth of it withheld, and a page
    carrying one short line that is gone entirely. A mean of the shares says
    55% of this release is withheld, which is a sentence a reporter would put
    in a first paragraph and which is not true of anything. The content-weighted
    figure says 12.2%, because the second page holds a fortieth as much.
    """
    dense = counted_page(
        1,
        words=filling(0.0, 0.0, 1.0, 0.8, count=4),
        redactions=[Redaction(box=Box(0, 0, 0.1, 0.8), kind=RedactionKind.VECTOR)],
        redaction_ratio=0.1,
    )
    one_line = counted_page(
        2,
        redactions=[Redaction(box=Box(0, 0, 0.2, 0.025), kind=RedactionKind.VECTOR)],
        redaction_ratio=1.0,
    )
    doc = Document(
        id="a", title="A", filename="a.pdf", sha256="a" * 64, size_bytes=1,
        pages=[dense, one_line],
    )

    stats = summarise(Collection(documents=[doc]))

    mean_of_shares = (dense.redaction_ratio + one_line.redaction_ratio) / 2
    assert mean_of_shares == pytest.approx(0.55)
    # 512000 pt² of content on the first page, 3200 on the second.
    assert stats.redacted_pages_area_pt == pytest.approx(515_200.0)
    assert stats.withheld_area_pt == pytest.approx(51_200.0 + 3_200.0)
    assert stats.redaction_ratio == pytest.approx(54_400.0 / 515_200.0)
    assert stats.redaction_ratio < 0.13


def test_the_collection_figure_is_the_per_page_figures_weighted_by_content():
    """The number on the front page has to be reconstructible from the pages.

    Somebody who reads "35% withheld" on the front page and then sees 96%, 6%,
    5%, 3% and 3% beside individual pages on ``withheld/index.html`` will try to
    get from one to the other. They can: it is those shares weighted by each
    page's content area, and nothing else.
    """
    pages = [
        counted_page(
            n,
            words=filling(0.0, 0.0, 1.0, height),
            redactions=[Redaction(box=Box(0, 0, share, height), kind=RedactionKind.VECTOR)],
            redaction_ratio=share,
        )
        for n, (share, height) in enumerate(((0.25, 0.8), (0.5, 0.2), (0.75, 0.5)), start=1)
    ]
    doc = Document(
        id="a", title="A", filename="a.pdf", sha256="a" * 64, size_bytes=1, pages=pages
    )

    stats = summarise(Collection(documents=[doc]))

    areas = [
        redaction.content_area(
            p.redactions, [w.box for w in p.words], (p.width_pt, p.height_pt)
        )[1]
        for p in pages
    ]
    expected = sum(p.redaction_ratio * a for p, a in zip(pages, areas, strict=True)) / sum(areas)
    assert stats.redaction_ratio == pytest.approx(expected)


