CLEAR_Y = 200.0
"""A band of the page, in PDF user space, that ``synth.born_digital_pdf`` leaves
empty: its body text stops around y=247. A box put here covers nothing but what
the fixture deliberately hides under it, so a recovered leak is exactly the
planted string and not the planted string interleaved with the prose."""


def fast_config(**overrides) -> Config:
    """The default configuration, made cheap enough to run in a test.

    Only rendering is changed. The OCR mode, the language codes and the safety
    policy are the shipped defaults on purpose: they are what is under test.
    """
    cfg = Config()
    cfg.render.dpi = 100
    cfg.render.widths = [600]
    cfg.render.thumb_width = 120
    cfg.render.formats = ["webp"]
    cfg.search.enabled = False
    for key, value in overrides.items():
        setattr(cfg, key, value)
    return cfg


def collection_in(root: Path, cfg: Config | None = None):
    return build_collection(root, cfg or fast_config(), root.parent / "out", workers=1)


