"""From a folder of files to a Collection: the decisions, end to end.

These tests run the real pipeline over real PDFs generated by ``tests/synth.py``
- poppler renders them, Tesseract reads the ones with no text layer - because
the properties that matter here are exactly the ones a stub would paper over:
whether the PDF's own text is trusted, whether a page that looks like garbage
gets read again from the pixels, and whether a failed redaction is caught before
anything is written.

Speed is a feature of a test suite that people run, so every document here is
one to three pages, ``workers=1`` (the pool adds a second of process startup and
hides the traceback of anything that goes wrong in it), and the render config is
one small WebP - AVIF encoding is slow and is ``ingest/raster.py``'s business,
not this module's.

The safety tests are the reason this file exists. Guarantee 4 says text a
redaction failed to remove is never published; a test that only checks the flag
would pass while the text sat in ``data/<doc>/<n>.json``, so they assert on the
built output instead.
"""

