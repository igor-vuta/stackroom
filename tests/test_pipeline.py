def latin_word(text: str) -> Word:
    return Word(text=text, box=Box(0.1, 0.2, 0.3, 0.02), conf=88, line=3)


def test_a_cjk_word_becomes_one_word_per_character():
    """Pagefind re-segments CJK itself and counts one token per character.

    If a word here spans three characters and the index counts three, every
    highlight after it on the page lands on the wrong glyph.
    """
    split = _split_cjk([Word(text="機密文書", box=Box(0.2, 0.4, 0.4, 0.03), conf=71, line=2)])
    assert [w.text for w in split] == ["機", "密", "文", "書"]
    assert all(w.line == 2 and w.conf == 71 for w in split)


def test_the_boxes_of_a_split_word_tile_the_box_it_came_from():
    """Square, evenly spaced glyphs: proportional division is very nearly exact."""
    original = Word(text="機密文書", box=Box(0.2, 0.4, 0.4, 0.03), line=0)
    split = _split_cjk([original])
    assert sum(w.box.w for w in split) == pytest.approx(original.box.w)
    assert split[0].box.x == pytest.approx(0.2)
    assert split[-1].box.x2 == pytest.approx(original.box.x2)
    for left, right in pairwise(split):
        assert left.box.x2 == pytest.approx(right.box.x)
        assert left.box.y == original.box.y and left.box.h == original.box.h


@pytest.mark.parametrize("text", ["hello", "authority,", "(b)(6)", "12345", "COMMISSION"])
def test_a_latin_word_is_left_exactly_as_it_was(text):
    """The split must not touch the scripts it is not for.

    A Latin word broken into letters would multiply the token count by six and
    desynchronise the index on every English page in the archive.
    """
    word = latin_word(text)
    split = _split_cjk([word])
    assert len(split) == 1
    assert split[0] is word, "an untouched word should not even be copied"


