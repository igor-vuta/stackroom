def test_hidden_text_never_reaches_the_page_object(failed_redaction):
    """Guarantee 4, at the seam where the site builder would read it.

    Even in ``warn`` mode this text is dropped: what the operator publishes is
    the document, not our transcription of what somebody tried to remove.
    """
    _, outcomes = failed_redaction
    page = outcomes[0].page
    assert page.words, "dropping the covered words must not empty the page"
    for token in ("Gregory", "Aldana"):
        assert not [w for w in page.words if token in w.text]
        assert not [line for line in page.lines if token in line]
    assert "Aldana" not in page.token_text


def test_hidden_text_never_reaches_the_built_site(tmp_path, failed_redaction):
    """The assertion that would have caught it in ``data/<doc>/<n>.json``.

    The published original is the exception, and deliberately so: guarantee 2
    says the file is downloadable byte for byte, and a released PDF with a
    failed redaction in it is evidence of the failure. Everything Stackroom
    *generates* has to be clean.
    """
    collection, outcomes = failed_redaction
    cfg = fast_config()
    cfg.safety.hidden_text = "warn"
    out = tmp_path / "site"
    build_site(collection, cfg, out)

    generated = [
        path
        for path in out.rglob("*")
        if path.is_file() and "files" not in path.relative_to(out).parts
    ]
    assert generated
    for path in generated:
        text = path.read_bytes().decode("utf-8", errors="ignore")
        for token in ("Gregory", "Aldana"):
            assert token not in text, f"leaked into {path.relative_to(out)}"

    original = out / "files" / "release.pdf"
    assert original.is_file(), "the original must still be published"
    assert outcomes[0].hidden, "the fixture is only meaningful if a leak was planted"


