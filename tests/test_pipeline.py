def prose_pdf(path: Path, text: str, font_name: str, pages: int = 1) -> Path:
    """A born-digital PDF of *text*, in a font that can draw it.

    ``synth.born_digital_pdf`` uses Helvetica, which has no Cyrillic and no
    Devanagari, so a non-Latin fixture needs its own generator. Everything else
    about the page is deliberately ordinary: real glyphs, a real text layer,
    nothing wrong with it.
    """
    from reportlab.lib.pagesizes import LETTER
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.pdfgen import canvas

    font_path = _FONTS[font_name]
    if not Path(font_path).is_file():  # pragma: no cover - depends on the host
        pytest.skip(f"{font_name} is not installed on this machine")
    pdfmetrics.registerFont(TTFont(font_name, font_path))
    _width, height = LETTER
    c = canvas.Canvas(str(path), pagesize=LETTER)
    words = text.split()
    for _ in range(pages):
        c.setFont(font_name, 11)
        y, line, i = height - 90, [], 0
        while y > 110:
            line.append(words[i % len(words)])
            i += 1
            if len(line) >= 9:
                c.drawString(72, y, " ".join(line))
                line = []
                y -= 16
        c.showPage()
    c.save()
    return path


def test_a_russian_page_in_a_collection_declared_english_is_left_alone(tmp_path):
    """The defect, end to end, in the configuration an operator really has.

    ``ocr.languages`` is Tesseract's list - what the recogniser should expect
    on a *scan*. It used to be handed to the quality check as the list of
    languages whose stopwords to count, so a born-digital Russian page in a
    collection declared ``["eng"]`` scored a stopword ratio of zero, was told
    "the PDF's own text layer does not read as language; re-OCR this page", and
    was either re-read by an English-only recogniser or published as
    unreadable - telling the reader that search cannot find anything on a page
    whose text is perfect.

    Declaring ``["eng", "rus"]`` is not the workaround: it measurably degrades
    the English scans in the same collection.
    """
    root = tmp_path / "papers"
    root.mkdir()
    prose_pdf(root / "russian.pdf", RUSSIAN_PROSE, "DejaVu")
    _, outcomes = collection_in(root)

    page = outcomes[0].page
    assert page.source is TextSource.EMBEDDED, outcomes[0].warnings
    assert page.quality.verdict is PageVerdict.GOOD, page.quality.reasons
    assert page.quality.stopword_ratio > 0.25
    assert page.language == "ru"
    assert not any("re-ocr" in r.lower() for r in page.quality.reasons)
    assert not any("unusable" in w for w in outcomes[0].warnings)


