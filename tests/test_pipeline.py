def counted_page(number: int, **kwargs) -> Page:
    """A page on a square 800pt sheet, where one grid cell is exactly 1 pt².

    `redaction.content_area` measures on a grid RATIO_GRID (800) cells wide and
    as many tall as the aspect ratio asks for, so a square 800pt page gives an
    800x800 grid and an area in square points that is just the number of cells.
    That is what makes the arithmetic below checkable with a pencil.
    """
    kwargs.setdefault("width_pt", 800.0)
    kwargs.setdefault("height_pt", 800.0)
    return Page(number=number, **kwargs)


def filling(x: float, y: float, w: float, h: float, count: int = 3) -> list[Word]:
    """*count* words whose boxes together fill exactly the given rectangle."""
    step = w / count
    return [
        Word(text="w", box=Box(x + i * step, y, step, h)) for i in range(count)
    ]


def test_the_collection_summary_counts_what_it_says_it_counts():
    """Every number on the front page and in the manifest comes from here.

    Hand-computed against a collection small enough to check by eye, because a
    statistic that is wrong is worse than one that is missing: it is quoted.

    Four pages, on square 800pt sheets so that one grid cell is one square
    point:

    ======  ===============================  ==========  =====  =========
    page    content                          area (pt²)  share  withheld
    ======  ===============================  ==========  =====  =========
    a1      text over the top half, a strip       320000   0.10      32000
            of it blacked out
    a2      blacked out end to end: one box       640000   1.00     640000
            over the whole sheet, no words
            left at all
    a3      blank: no text, no boxes                   0      -          -
    b1      text over the top half, nothing       320000   0.00          0
            withheld
    ======  ===============================  ==========  =====  =========

    So:

    * ``redaction_ratio`` = 672000 / 960000 = **0.70** - the withheld area over
      the content of the two pages that carry redactions, which is what the
      front page prints and what the sentence beside it names.
    * ``redaction_ratio_collection`` = 672000 / 1280000 = **0.525** - the same
      numerator over every page.

    Neither is the mean of the per-page shares, and that is the point. The old
    code averaged the shares of the pages that had any text, which here is
    (0.10 + 0.00) / 2 = **0.05**: page a2, blacked out from edge to edge, has no
    surviving words and so did not appear in the statistic at all.
    """
    a1 = counted_page(
        1,
        words=filling(0.0, 0.0, 1.0, 0.5),
        source=TextSource.EMBEDDED,
        redactions=[Redaction(box=Box(0, 0, 0.1, 0.5), kind=RedactionKind.VECTOR)],
        redaction_ratio=0.1,
        exemptions=["b(6)"],
        language="en",
    )
    a2 = counted_page(
        2,
        source=TextSource.NONE,
        quality=OcrQuality(verdict=PageVerdict.SUSPECT),
        redactions=[Redaction(box=Box(0, 0, 1.0, 1.0), kind=RedactionKind.VECTOR)],
        redaction_ratio=1.0,
        exemptions=["b(6)", "b(7)(C)"],
    )
    a3 = counted_page(3, source=TextSource.NONE, quality=OcrQuality(verdict=PageVerdict.BLANK))
    b1 = counted_page(
        1,
        words=filling(0.0, 0.0, 1.0, 0.5, count=2),
        source=TextSource.OCR_OVERRIDE,
        quality=OcrQuality(verdict=PageVerdict.PICTORIAL),
        language="fr",
    )

    # The shares above are the ones `ingest/redaction.py` would measure for
    # these boxes, so the fixture cannot drift away from the real thing.
    for page in (a1, a2, b1):
        assert page.redaction_ratio == pytest.approx(
            redaction.redaction_ratio(
                page.redactions, [w.box for w in page.words], (page.width_pt, page.height_pt)
            )
        )

    first = Document(
        id="a", title="A", filename="a.pdf", sha256="a" * 64, size_bytes=1000,
        pages=[a1, a2, a3],
    )
    second = Document(
        id="b", title="B", filename="b.pdf", sha256="b" * 64, size_bytes=100, pages=[b1],
    )

    stats = summarise(Collection(documents=[first, second]))

    assert stats.documents == 2
    assert stats.pages == 4
    assert stats.words == 5
    assert stats.pages_with_redactions == 2
    assert stats.redaction_boxes == 2

    assert stats.redacted_pages_area_pt == pytest.approx(960_000.0)
    assert stats.collection_area_pt == pytest.approx(1_280_000.0)
    assert stats.withheld_area_pt == pytest.approx(672_000.0)
    assert stats.redaction_ratio == pytest.approx(0.70), "withheld area over the redacted pages"
    assert stats.redaction_ratio_collection == pytest.approx(0.525), "over the whole collection"
    assert stats.unmeasured_pages == 1, "the blank page can be measured neither way"

    assert stats.unreadable_pages == 1
    assert stats.pictorial_pages == 1
    assert stats.blank_pages == 1
    assert stats.ocr_pages == 1, "OCR and OCR-override are both recognised pages"
    assert stats.exemption_counts == {"b(6)": 2, "b(7)(C)": 1}
    assert list(stats.exemption_counts) == ["b(6)", "b(7)(C)"], "commonest first"
    assert stats.languages == ["en", "fr"]
    assert stats.bytes_total == 1100


