def test_leak_failed_redaction_is_found_and_recovered(tmp_path):
    """A black box painted over live text is reported, with the text.

    This is the whole point of the module. The operator has to be shown what
    leaked, or they cannot judge how bad it is.
    """
    path = memo(tmp_path, [synth.RedactionSpec(90, CLEAR_Y, 200, 14, hidden_text="Gregory Aldana")])
    page = raw_page(path)

    for label, renderer in both_ways(path):
        found = find_hidden_text(page, crop_renderer=renderer)
        assert len(found) == 1, f"{label}: expected exactly one leak, got {found}"
        assert found[0].text == "Gregory Aldana", label
        assert found[0].redacted_repr() == "####### ######", label
        assert found[0].box.overlap_ratio(Box(0.14, 0.72, 0.34, 0.03)) > 0.9, label


def test_leak_same_colour_text_drawn_after_the_box(tmp_path):
    """Black text painted *on top of* a black box is still invisible.

    Draw order alone would clear this one - the text is painted last, so it is
    "on top" - but you cannot read black ink on a black box. This is a common
    shape for the bug: a tool stamps the box, then writes the text into it.
    """
    page = RawPage(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=10)],
        chars=text_run("Marta Oyelaran", x=92, top=602, seq=20),  # after the box
    )
    for renderer in (flat_renderer(), None):
        found = find_hidden_text(page, crop_renderer=renderer)
        assert [f.text for f in found] == ["Marta Oyelaran"]


