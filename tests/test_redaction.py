# 4. The ledger: which filled rectangles count as a redaction
#
# "N pages withheld, X% of content" is the most consequential number this tool
# prints, and a born-digital PDF is full of filled rectangles that withhold
# nothing at all. These tests are the ones that keep that number honest.
# ==========================================================================


def covered_text(fill, *, text_first=True, seq_rect=100):
    """A rectangle of *fill* colour with a line of text at the same place.

    ``text_first`` decides which of the two the content stream paints first,
    which is the whole difference between a redaction and a table cell.
    """
    return RawPage(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=seq_rect, colour=fill)],
        chars=text_run("Underneath", x=92, top=602, seq=1 if text_first else seq_rect + 1),
    )


def bare_rect(fill):
    """A rectangle of *fill* colour with nothing under it at all."""
    return RawPage(rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=100, colour=fill)])


def test_ledger_a_white_rectangle_over_nothing_is_furniture():
    """A knockout box clearing space for a stamp is not a redaction.

    Real PDFs are full of these - cell fills, header knockouts, whiteout over a
    scanning artefact, form backgrounds. One per page in the ledger and every
    percentage in the archive is wrong.
    """
    result = analyse_page(bare_rect(WHITE), crop_renderer=flat_renderer(255))
    assert result.redactions == []
    assert result.hidden == []


def test_ledger_a_white_rectangle_over_live_text_is_a_redaction_and_a_leak():
    """White-on-white: the box withheld something, and badly.

    A white rectangle dropped over text that is already on the page obliterates
    it on screen and leaves every word of it in the file. It belongs in the
    ledger *and* it stops the build.
    """
    page = covered_text(WHITE, text_first=True)
    for renderer in (flat_renderer(255), None):
        assert [f.text for f in find_hidden_text(page, crop_renderer=renderer)] == [
            "Underneath"
        ]
    result = analyse_page(page, crop_renderer=flat_renderer(255))
    assert [r.kind for r in result.redactions] == [RedactionKind.VECTOR]
    assert [f.text for f in result.hidden] == ["Underneath"]


def test_ledger_a_black_rectangle_over_nothing_is_a_redaction():
    """A box over a photograph or a signature has no characters to find.

    Nothing in the content stream says what was there, so darkness is the only
    evidence available - and it is enough: a reader cannot see through it.
    """
    result = analyse_page(bare_rect(BLACK), crop_renderer=flat_renderer(0))
