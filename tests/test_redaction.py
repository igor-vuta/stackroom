def test_a_box_hanging_off_the_page_is_still_mapped_correctly():
    """The crop contract, at the one place the two sides of it disagree.

    ``ingest/pdf.py`` deliberately does not clamp rectangles to the media box -
    full-bleed content is real, and moving a redaction box away from what it
    covers would be worse. Every renderer in the project deliberately does
    clamp, because there are no pixels outside the page. Ask for a box that
    hangs off the edge and you get back an image of *less* than you asked for,
    and every coordinate mapped into it is then wrong by the overhang - which
    silently clears real leaks, because the characters land on the wrong pixels.

    So the box is clipped to the page before it is asked for. The renderer here
    is a copy of the pipeline's, floor/ceil and clamped, and the page is built
    so that the wrong mapping lands the characters on lettering-like texture
    and the right one lands them on solid black.
    """
    page_px = Image.new("L", (1000, 500), 255)
    draw = ImageDraw.Draw(page_px)
    draw.rectangle([0, 200, 299, 249], fill=0)  # the on-page part of the box
    for stripe in range(100, 280, 8):  # lettering-like texture inside it
        draw.rectangle([stripe, 200, stripe + 3, 249], fill=255)

    def pipeline_cropper(box: Box) -> Image.Image:
        # Identical to pipeline._in_memory_cropper: outwards, then clamped.
        import math

        x0 = max(0, min(1000, math.floor(box.x * 1000)))
        y0 = max(0, min(500, math.floor(box.y * 500)))
        x1 = max(0, min(1000, math.ceil(box.x2 * 1000)))
        y1 = max(0, min(500, math.ceil(box.y2 * 500)))
        if x1 <= x0 or y1 <= y0:
            raise ValueError("empty crop")
        return page_px.crop((x0, y0, x1, y1))

    # The rectangle starts 20% of the page width off the left edge. The
    # characters are painted after it and in another colour, so the content
    # stream cannot vouch for them: only the pixels can.
    page = RawPage(
        rects=[Rect(x0=-122.4, top=316.8, x1=183.6, bottom=396.0, seq=10, colour=BLACK)],
        chars=text_run("ABC", x=12.24, top=332.64, seq=99, size=20, colour=WHITE),
    )
    found = find_hidden_text(page, crop_renderer=pipeline_cropper)
    assert [f.text for f in found] == ["ABC"]


