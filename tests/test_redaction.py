"""What must never be published, and what must never be claimed.

Guarantee 4 in ``docs/ARCHITECTURE.md`` says text that a redaction failed to
remove is never published: the build stops instead. This file is where that
guarantee is checked, so the tests are written to be read rather than merely to
pass. Each one names the property it defends in its docstring, and the two
kinds of failure are kept apart on purpose:

* **A false negative in hidden text can burn a source.** Those tests are
  labelled ``leak``. Several run twice, once against a real rendering of the
  page and once blind, because the pipeline runs in both configurations and
  the property has to hold in both of them.
* **A false positive in visible redactions makes the ledger lie.** Those tests
  are labelled ``decoy`` and each one names the specific thing that would
  otherwise have been counted as a redaction.

Everything is generated by ``tests/synth.py``. No fixtures, no third party's
documents, and no network.
"""

