def test_a_flat_box_does_not_overrule_a_character_that_can_be_seen():
    """The mechanism, stated on its own so it cannot be lost by accident.

    ``box_is_flat`` is a statistic over the whole rectangle and one line of
    lettering is a rounding error in it. It may therefore answer only for
    characters that cannot be measured on their own, and only while no
    character contradicts it.

    The rendering here is a page-sized box, flat black except for the cells of
    seven characters, which are white: 0.15% of the pixels, which reads std
    10.0 - inside the cut, so the box-level test says *flat* - while every one
    of those seven cells is half white. The characters win, and the numbers are
    written down in the assertions so that a change to either threshold shows
    up here as a failure rather than as a silently different answer.
    """
    page = RawPage(
        rects=[Rect(x0=50, top=52, x1=562, bottom=740, seq=100)],
        chars=text_run("VISIBLE", x=60, top=60, seq=200, size=12, colour=WHITE),
    )
    crop_box = Box(50 / 612, 52 / 792, 512 / 612, 688 / 792)

    def lettering_on_a_black_page(box: Box) -> Image.Image:
        img = Image.new("L", (1000, 1344), 0)
        draw = ImageDraw.Draw(img)
        # One white stem in each glyph's cell. text_run puts the seven glyphs
        # at 60pt + 6.6pt each, 12pt tall; the crop covers 50..562 x 52..740pt,
        # so a cell is 12.9px wide and starts at 19.5 + 12.9i.
        for i in range(7):
            left = 19 + round(i * 12.9)
            draw.rectangle([left, 15, left + 5, 39], fill=255)
        return img

    crop = _Crop(crop_box, lettering_on_a_black_page(crop_box))
    assert crop.box_is_flat(), "the whole-box test has to be saying 'flat' here"
    assert crop.hides(Box(60 / 612, 60 / 792, 6.6 / 612, 12 / 792)) is False

    assert find_hidden_text(page, crop_renderer=lettering_on_a_black_page) == []


def test_genuine_leaks_survive_at_page_scale(tmp_path):
    """The three real shapes of a failed redaction, at the size that broke.

    A page-sized box is where ``box_is_flat`` used to decide everything, so
    demoting it has to be shown not to have cost any of them:

    * text painted before a covering rectangle - the ordinary failed redaction;
    * text painted after it in the rectangle's own ink - black on black;
    * a white rectangle dropped over live text - the white knockout, where the
      box is invisible and the words are the only thing that was there.
    """
    from reportlab.lib.pagesizes import LETTER
    from reportlab.pdfgen import canvas

    width, _height = LETTER

    def body(c, ink):
        c.setFillColorRGB(*ink)
        c.setFont("Helvetica", 10.5)
        y = 730.0
        for _ in range(38):
            c.drawString(60, y, "Marta Oyelaran met the contractor that morning.")
            y -= 15.2

    cases = {"before": (BLACK, True, BLACK), "after": (BLACK, False, BLACK),
             "knockout": (WHITE, True, BLACK)}
    for name, (fill, text_first, ink) in cases.items():
        path = tmp_path / f"page-{name}.pdf"
        c = canvas.Canvas(str(path), pagesize=LETTER)
        if text_first:
            body(c, ink)
        c.setFillColorRGB(*fill)
        c.rect(50, 140, width - 100, 600, stroke=0, fill=1)
        if not text_first:
            body(c, ink)
        c.showPage()
        c.save()

        page = raw_page(path)
        for label, renderer in both_ways(path):
            found = find_hidden_text(page, crop_renderer=renderer)
            assert found, f"{name} ({label}): a real leak went unreported"
            assert "Marta Oyelaran" in found[0].text, f"{name} ({label}): {found[0].text[:60]}"


def test_a_glyph_flush_with_the_edge_of_the_box_is_still_hidden(tmp_path):
    """The crop's outermost pixels are paper, and must not read as a glyph.

    ``render_page_crop`` rounds its crop outwards, so a character's cell at the
    very edge of a rectangle can reach a sliver of the page behind it. That did
    not matter while ``box_is_flat`` was answering for the whole box; now that
    each character answers for itself it decides real findings, and a genuinely
    buried glyph must not read as legible because of where the box happened to
    land between two pixels. Sweeping the box across a pixel is the reproducer:
    at two thirds of a pixel the cell went from std 0.0 to std 56.9.
    """
    from reportlab.lib.pagesizes import LETTER
    from reportlab.pdfgen import canvas

    for step in range(8):
        x = 90.0 + step / 8.0
        path = tmp_path / f"flush-{step}.pdf"
        c = canvas.Canvas(str(path), pagesize=LETTER)
        c.setFillColorRGB(0, 0, 0)
        c.setFont("Helvetica", 10.5)
        c.drawString(x, 603.0, "Marta Oyelaran")   # painted first: a real leak
        c.rect(x, 600.0, 90.0, 16.0, stroke=0, fill=1)
        c.showPage()
        c.save()

        found = find_hidden_text(raw_page(path), crop_renderer=pdf_renderer(path, resolution=150))
        assert found, f"box offset by {step}/8 of a pixel lost the leak under it"


