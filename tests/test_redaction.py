# --------------------------------------------------------------------------
# stand-ins for ingest/pdf.py
#
# That module owns RawPage/RawChar/RawRect and may not exist yet. Everything
# under test reads a small structural contract - x0/top/x1/bottom in points,
# a colour, and `seq`, the position in the content stream - so these three
# dataclasses are a complete stand-in for it, and building a page by hand is
# the only way to test the awkward cases in isolation.
# --------------------------------------------------------------------------


@dataclass
class Char:
    text: str
    x0: float
    top: float
    x1: float
    bottom: float
    seq: int
    colour: tuple[float, float, float] = BLACK


@dataclass
class Rect:
    x0: float
    top: float
    x1: float
    bottom: float
    seq: int
    colour: tuple[float, float, float] = BLACK
    fill: bool = True
    opacity: float = 1.0


@dataclass
class RawPage:
    width: float = 612.0
    height: float = 792.0
    chars: list[Char] = field(default_factory=list)
    rects: list[Rect] = field(default_factory=list)


def text_run(text: str, x: float, top: float, *, seq: int, size: float = 10.5,
             colour: tuple[float, float, float] = BLACK) -> list[Char]:
    """A line of monospaced-ish characters starting at ``(x, top)``, in points."""
    advance = size * 0.55
    return [
        Char(
            text=ch,
            x0=x + i * advance,
            top=top,
            x1=x + (i + 1) * advance,
            bottom=top + size,
            seq=seq + i,
            colour=colour,
        )
        for i, ch in enumerate(text)
    ]


def flat_renderer(level: int = 0):
    """A crop renderer that says every box is a solid block of one colour."""
    return lambda box: Image.new("L", (120, 40), level)


def textured_renderer(box_level: int = 0, ink_level: int = 255):
    """A crop renderer that says every box has lettering standing out on it.

    This is what a highlight over live text looks like, and what a black box
    with white lettering painted on top looks like: the glyphs are in the
    pixels, so a reader can see them.
    """

    def render(box: Box) -> Image.Image:
        img = Image.new("L", (160, 40), box_level)
        draw = ImageDraw.Draw(img)
        for i in range(0, 160, 8):
            draw.rectangle([i + 2, 8, i + 5, 32], fill=ink_level)
        return img

    return render


# --------------------------------------------------------------------------
# stand-ins for ingest/raster.py, driven by a real PDF
# --------------------------------------------------------------------------


def _stream_objects(container):
    """Every drawable in content-stream order, descending into form XObjects.

    ``ingest/pdf.py`` is the module that owes the pipeline a real ``seq``; this
    is the same idea done crudely, and it is good enough to drive the tests
    because pdfminer with no layout analysis emits objects in paint order.
    """
    from pdfminer.layout import LTFigure

    for obj in container:
        if isinstance(obj, LTFigure):
            yield from _stream_objects(obj)
        else:
            yield obj


def raw_page(path, index: int = 0) -> RawPage:
    """Read a synthetic PDF into the stand-in objects above."""
    import pdfplumber
    from pdfminer.layout import LTChar, LTRect

    with pdfplumber.open(path) as pdf:
        page = pdf.pages[index]
        height = page.height
        chars: list[Char] = []
        rects: list[Rect] = []
        for seq, obj in enumerate(_stream_objects(page.layout)):
            if isinstance(obj, LTChar):
                chars.append(
                    Char(
                        text=obj.get_text(),
                        x0=obj.x0,
                        top=height - obj.y1,
                        x1=obj.x1,
                        bottom=height - obj.y0,
                        seq=seq,
                        colour=obj.graphicstate.ncolor,
                    )
                )
            elif isinstance(obj, LTRect):
                rects.append(
                    Rect(
                        x0=obj.x0,
                        top=height - obj.y1,
                        x1=obj.x1,
                        bottom=height - obj.y0,
                        seq=seq,
                        colour=getattr(obj, "non_stroking_color", None),
                        fill=bool(obj.fill),
                    )
                )
        return RawPage(width=page.width, height=page.height, chars=chars, rects=rects)


def pdf_renderer(path, index: int = 0, resolution: int = 200):
    """A ``crop_renderer`` over a real rendering of the page.

    Stands in for ``functools.partial(raster.render_page_crop, path, page)``.
    Renders once and crops, which is the contract the module documents: the
    image covers exactly the box it was asked for.
    """
    import pdfplumber

    with pdfplumber.open(path) as pdf:
        page = pdf.pages[index]
        try:
            image = page.to_image(resolution=resolution).original.convert("L")
        except Exception as exc:  # pragma: no cover - depends on the host
            pytest.skip(f"no page renderer available here: {exc!r}")
    width, height = image.size

    def render(box: Box) -> Image.Image:
        left, top = int(box.x * width), int(box.y * height)
        right, bottom = round(box.x2 * width), round(box.y2 * height)
        return image.crop((left, top, max(right, left + 1), max(bottom, top + 1)))

    return render


# The page body of a synthetic memo runs from about 104pt to 545pt down the
# page. Boxes for the hidden-text tests go below it, so that the only thing
# under them is the text the test put there.
CLEAR_Y = 200.0  # PDF user space, measured up from the bottom
CLEAR_Y2 = 170.0


def memo(tmp_path, specs, name="memo.pdf"):
    path = tmp_path / name
    synth.born_digital_pdf(path, pages=1, redactions={1: specs})
    return path


def both_ways(path):
    """The two configurations every hidden-text property must hold in."""
    return [("with a rendering", pdf_renderer(path)), ("blind", None)]


