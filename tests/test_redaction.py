def test_it_fits_the_real_raw_page_and_the_real_renderer(tmp_path):
    """The contract this module states, checked against the modules that meet it.

    Everything above drives ``redaction.py`` through stand-ins, on purpose:
    those tests have to keep working while ``ingest/pdf.py`` is still being
    written. This one closes the loop. ``RawPage`` carries page-relative boxes
    and spells its colours ``fill_color``/``color``; ``render_page_crop`` takes
    ``(pdf, page, box)`` and rounds its crop outwards. If either of those
    drifts, the leak check quietly stops finding leaks, so it should be a
    failing test and not a surprise in production.
    """
    pdf = pytest.importorskip("stackroom.ingest.pdf")
    raster = pytest.importorskip("stackroom.ingest.raster")

    path = memo(
        tmp_path,
        [
            synth.RedactionSpec(90, CLEAR_Y, 200, 14, hidden_text="Gregory Aldana"),
            synth.RedactionSpec(
                90, CLEAR_Y2, 200, 14, hidden_text="Visible Overlay", draw_text_after=True
            ),
        ],
    )
    try:
        raster.page_geometry(path)
    except Exception as exc:  # pragma: no cover - no poppler on this host
        pytest.skip(f"pdftoppm/pdfinfo unavailable: {exc!r}")

    with pdf.open_pdf(path) as handle:
        page = pdf.read_page(handle, 0)

    render = functools.partial(raster.render_page_crop, path, 1)
    result = analyse_page(page, crop_renderer=render)
    assert [f.text for f in result.hidden] == ["Gregory Aldana"]
    assert result.warnings == []  # every finding confirmed against the pixels
    assert len(result.redactions) == 2
    assert find_hidden_text(page) == result.hidden  # and the same answer blind


def test_the_field_names_ingest_pdf_uses_are_the_ones_this_module_reads():
    """A rename in ``ingest/pdf.py`` must fail here, not degrade the check there.

    This module reads its inputs through alias tables so that a test can drive
    it with a three-line stand-in. The cost of that flexibility is that a
    renamed field on the real ``RawRect`` stops being a crash and becomes a
    shrug: ``_field`` falls through to the default, the same-colour half of the
    hidden-text test stops firing, and nothing says anything. This is the alarm.
    """
    from stackroom.ingest import pdf as pdf_mod
    from stackroom.ingest import redaction as module

    rect_names = {f.name for f in dataclasses.fields(pdf_mod.RawRect)}
    char_names = {f.name for f in dataclasses.fields(pdf_mod.RawChar)}
    page_names = {f.name for f in dataclasses.fields(pdf_mod.RawPage)} | {"has_zorder"}

    for owner, names, table, what in (
        ("RawRect", rect_names, module._COLOUR, "a fill colour"),
        ("RawChar", char_names, module._COLOUR, "a colour"),
        ("RawRect", rect_names, module._SEQ, "a draw order"),
        ("RawChar", char_names, module._SEQ, "a draw order"),
        ("RawPage", page_names, module._WIDTH, "a width"),
        ("RawPage", page_names, module._HEIGHT, "a height"),
        ("RawPage", page_names, module._ORDERED, "whether its draw order is usable"),
    ):
        assert names & set(table), (
            f"ingest/pdf.py's {owner} no longer carries {what} under any of {table!r}; "
            "redaction.py reads it through that table and would silently stop checking"
        )


def test_a_shape_with_no_colour_field_at_all_is_reported():
    """"Unknown colour" and "no colour field" must not look alike.

    A rect whose ``fill_color`` is None is an ordinary PDF telling us it used a
    colour space we decline to guess at, and the same-colour test simply does
    not fire. A rect with no colour field *at all* is this module reading a
    shape it does not understand - a renamed field, a new producer object - and
    half the hidden-text test is not running. One of those is a page note.
    """

    @dataclass
    class Colourless:
        x0: float
        top: float
        x1: float
        bottom: float
        seq: int
        fill: bool = True

    page = RawPage(
        rects=[Colourless(x0=90, top=600, x1=290, bottom=616, seq=99)],
        chars=[
            Char(text=ch, x0=92 + i * 6, top=602, x1=98 + i * 6, bottom=612.5, seq=1 + i)
            for i, ch in enumerate("Anon Source")
        ],
    )
    notes = analyse_page(page).warnings
    assert any("no fill-colour field" in w for w in notes), notes

    # An honest None is not a broken contract and says nothing.
    known = RawPage(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=99, colour=None)],
        chars=[
            Char(text=ch, x0=92 + i * 6, top=602, x1=98 + i * 6, bottom=612.5, seq=1 + i)
            for i, ch in enumerate("Anon Source")
        ],
    )
    assert not any("no fill-colour field" in w for w in analyse_page(known).warnings)


def test_a_page_with_no_size_field_is_reported_rather_than_assumed_to_be_letter():
    """Every box is placed against the page size, so a missing one is not a detail.

    ``_WIDTH``/``_HEIGHT`` default to US Letter when a page carries neither
    name, which keeps a three-line stand-in working and would keep working
    silently after a rename in ``ingest/pdf.py`` - with every box on every page
    placed against the wrong sheet. That is a black box drawn somewhere it is
    not, which is the failure this module exists to prevent.
    """

    @dataclass
    class Sizeless:
        chars: list = field(default_factory=list)
        rects: list = field(default_factory=list)

    page = Sizeless(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=99)],
        chars=[
            Char(text=ch, x0=92 + i * 6, top=602, x1=98 + i * 6, bottom=612.5, seq=1 + i)
            for i, ch in enumerate("Anon Source")
        ],
    )
    notes = analyse_page(page).warnings
    assert any("no field naming a width" in w for w in notes), notes
    assert not any("no field naming" in w for w in analyse_page(RawPage(
        rects=page.rects, chars=page.chars
    )).warnings)


