def test_analyse_page_merges_vector_and_raster_and_warns_about_dark_bands():
    """A block in the pixels with no rectangle behind it is called out.

    A uniform dark band across a scan is genuinely indistinguishable from a
    redaction - it is flat, black, solid and rectangular because it is. It gets
    counted, and the warning says so rather than pretending otherwise.
    """
    page = RawPage(rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=100)], chars=[])
    image = synth.blank_page()
    draw = ImageDraw.Draw(image)
    draw.rectangle([187, 1250, 604, 1283], fill=0)  # the same box, in pixels
    draw.rectangle([100, 200, 1100, 260], fill=0)  # a dark band, not in the PDF

    result = analyse_page(page, image)
    kinds = [r.kind for r in result.redactions]
    assert kinds.count(RedactionKind.VECTOR) == 1, "the vector box must not be duplicated"
    assert kinds.count(RedactionKind.RASTER) == 1
    assert any("dark scan band" in w for w in result.warnings)


def test_analyse_page_derives_the_resolution_from_the_image():
    """A 300 dpi render must not turn a hairline rule into a redaction.

    The pixel thresholds are calibrated at 150 dpi. A page rendered at 300 has
    twice the pixels for the same ink, so a 3.6pt rule stands 15px tall - over
    the floor if you assume the resolution, comfortably under it once you work
    the resolution out from the image against the page size.
    """
    image = synth.blank_page(2550, 3300)  # letter at 300 dpi
    ImageDraw.Draw(image).rectangle([300, 1000, 1100, 1014], fill=0)  # 801 x 15 px

    assert analyse_page(RawPage(), image).redactions == []
    # The same pixels, told they are 150 dpi, are a redaction-shaped block.
    assert len(find_visible_redactions(image, dpi=150)) == 1


