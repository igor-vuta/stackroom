def test_a_fully_blacked_page_reads_1_0_not_0_63():
    """The denominator is the inked region, not the sheet of paper.

    A letter page blacked from margin to margin is 63% of the sheet, because an
    inch of margin all round is 37% of it. An archive that reports 63% for a
    page a reader cannot read a word of is not being cautious, it is wrong.
    """
    text_area = Box(72 / 612, 72 / 792, 468 / 612, 648 / 792)
    assert text_area.area == pytest.approx(0.626, abs=0.01)  # the wrong answer

    ratio = redaction_ratio([Redaction(box=text_area, kind=RedactionKind.VECTOR)], [], (612, 792))
    assert ratio == pytest.approx(1.0, abs=0.001)


def test_ratio_counts_area_not_bounding_boxes():
    """Two boxes on one line are not counted twice, and blank leading is not content.

    Bounding boxes over-count on both sides of the fraction; the union of areas
    is the only version that survives double-spaced text and overlapping boxes.
    """
    words = [Box(0.1, 0.1 + 0.05 * i, 0.6, 0.02) for i in range(10)]  # 10 lines
    two_on_one_line = [
        Redaction(box=Box(0.1, 0.1, 0.3, 0.02), kind=RedactionKind.VECTOR),
        Redaction(box=Box(0.3, 0.1, 0.3, 0.02), kind=RedactionKind.VECTOR),  # overlapping
    ]
    ratio = redaction_ratio(two_on_one_line, words, (612, 792))
    assert ratio == pytest.approx(0.1, abs=0.02)  # one line of ten, not two


def test_ratio_of_a_page_with_no_ink_is_zero():
    """A blank page is not a fully redacted page."""
    assert redaction_ratio([], [], (612, 792)) == 0.0


def test_content_area_is_the_ratio_written_as_two_numbers():
    """The share and the areas behind it come from one measurement.

    ``pipeline.summarise`` adds these areas up across a collection, and the
    front page prints the division. If the pair and the quotient could ever be
    computed differently, the collection figure and the per-page figures beside
    it would drift apart, which is precisely the bug this pair exists to close.
    """
    words = [Box(0.1, 0.1 + 0.05 * i, 0.6, 0.02) for i in range(10)]
    boxes = [Redaction(box=words[i], kind=RedactionKind.VECTOR) for i in range(3)]
    redacted, inked = content_area(boxes, words[3:], (612, 792))
    assert inked > 0
    assert redacted / inked == pytest.approx(redaction_ratio(boxes, words[3:], (612, 792)))


def test_content_area_is_in_square_points_so_pages_of_different_sizes_add_up():
    """A cell of the grid is not a fixed area, and pages are not one size.

    The grid is always 800 cells across, so a cell on a legal page covers more
    of the world than a cell on a postcard. Adding raw cell counts across a
    mixed collection would quietly weigh the small pages more heavily, so the
    areas come back in square points.
    """
    whole_page = [Redaction(box=Box(0, 0, 1, 1), kind=RedactionKind.VECTOR)]
    for width, height in ((612.0, 792.0), (612.0, 1008.0), (595.0, 842.0)):
        redacted, inked = content_area(whole_page, [], (width, height))
        assert redacted == pytest.approx(width * height, rel=0.001)
        assert inked == pytest.approx(width * height, rel=0.001)

    letter, _ = content_area(whole_page, [], (612.0, 792.0))
    legal, _ = content_area(whole_page, [], (612.0, 1008.0))
    assert legal > letter, "a bigger sheet blacked out is more content withheld"


def test_a_page_with_nothing_on_it_has_no_content_to_measure():
    """Zero, and not a division by it. The caller decides what that means."""
    assert content_area([], [], (612, 792)) == (0.0, 0.0)


def test_ratio_grows_monotonically_as_more_is_withheld():
    """Half the lines withheld reads about half, and it only goes up."""
    words = [Box(0.1, 0.1 + 0.04 * i, 0.6, 0.02) for i in range(10)]
    previous = -1.0
    for count in range(11):
        boxes = [Redaction(box=words[i], kind=RedactionKind.VECTOR) for i in range(count)]
        surviving = words[count:]
        ratio = redaction_ratio(boxes, surviving, (612, 792))
        assert ratio >= previous
        previous = ratio
    assert previous == pytest.approx(1.0, abs=0.001)


def test_a_scan_with_one_box_is_not_a_fully_withheld_page():
    """No text layer is not the same as no content.

    On a scan there are no word boxes to measure against, and measuring
    against the boxes alone would report every scanned page that has a
    redaction on it as 100% withheld - which would put a wall of red across the
    ledger for a production that is mostly readable. The ink in the rendering
    is the content region.
    """
    image = synth.typed_page(redactions=SCAN_BOXES)
    result = analyse_page(RawPage(chars=[], rects=[]), image)

    assert len(result.redactions) == 3
    assert 0.3 < result.ratio < 0.8, result.ratio
    assert result.ink_box is not None
    assert result.ink_box.w > 0.7 and result.ink_box.h > 0.7
    # Boxes must be plain floats: numpy scalars pass every test here and then
    # fail in json.dumps at the end of the build.
    assert all(type(v) is float for v in (result.ink_box.x, result.ink_box.w))
    assert isinstance(result.ratio, float) and type(result.ratio) is float


