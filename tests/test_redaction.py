def test_connected_components_matches_a_flood_fill():
    """The labeller is hand-written numpy; check it against the obvious version."""
    rng = np.random.default_rng(7)
    for _ in range(40):
        mask = rng.random((rng.integers(1, 20), rng.integers(1, 20))) < rng.uniform(0.1, 0.7)
        for connectivity in (4, 8):
            labels, components = connected_components(mask, connectivity=connectivity)
            assert _flood_fill_count(mask, connectivity) == len(components)
            for comp in components:
                selected = labels == comp.label
                rows, cols = np.nonzero(selected)
                assert (comp.x, comp.y) == (cols.min(), rows.min())
                assert comp.w == cols.max() - cols.min() + 1
                assert comp.h == rows.max() - rows.min() + 1
                assert comp.area == int(selected.sum())
            assert bool((labels > 0).any()) == bool(mask.any())
            assert not (labels > 0)[~mask].any()


def _flood_fill_count(mask: np.ndarray, connectivity: int) -> int:
    offsets = (
        [(-1, 0), (1, 0), (0, -1), (0, 1)]
        if connectivity == 4
        else [(dy, dx) for dy in (-1, 0, 1) for dx in (-1, 0, 1) if (dy, dx) != (0, 0)]
    )
    height, width = mask.shape
    seen = np.zeros_like(mask)
    total = 0
    for y in range(height):
        for x in range(width):
            if mask[y, x] and not seen[y, x]:
                total += 1
                stack = [(y, x)]
                seen[y, x] = True
                while stack:
                    cy, cx = stack.pop()
                    for dy, dx in offsets:
                        ny, nx = cy + dy, cx + dx
                        if 0 <= ny < height and 0 <= nx < width and mask[ny, nx] and not seen[ny, nx]:
                            seen[ny, nx] = True
                            stack.append((ny, nx))
    return total


def test_connected_components_labels_a_full_page_in_time():
    """A page has to be labelled in well under the frame the pipeline allows.

    Budget 150 ms for 1275x1650 at 150 dpi. Measured on this container: 24 ms
    for a typed page with 1,486 components. The assertion is loose enough not
    to flake on a loaded machine and tight enough to catch an accidental
    per-pixel Python loop, which would be about a hundred times over.
    """
    mask = binarise(to_gray(scanned_page_with_decoys()))
    assert mask.shape == (1650, 1275)
    connected_components(mask)  # warm up: the first big allocation is not the cost
    best = min(_time(lambda: connected_components(mask)) for _ in range(5))
    assert best < 0.150, f"{best * 1000:.0f} ms"


def _time(fn) -> float:
    start = time.perf_counter()
    fn()
    return time.perf_counter() - start


def test_components_are_labelled_in_raster_order():
    """Determinism: same bytes in, same order out (guarantee 6)."""
    mask = np.zeros((20, 20), dtype=bool)
    mask[15:18, 2:5] = True
    mask[2:5, 12:15] = True
    mask[2:5, 2:5] = True
    _, components = connected_components(mask)
    assert [(c.y, c.x) for c in components] == [(2, 2), (2, 12), (15, 2)]


def test_uniformity_and_the_empty_patch():
    """An empty patch is not uniform: we have not seen anything.

    Both callers depend on this. A redaction candidate we cannot measure is
    rejected, and a hidden-text box we cannot measure falls back to the content
    stream instead of being cleared by a crop that does not exist.
    """
    flat = np.full((30, 30), 7, dtype=np.uint8)
    assert uniformity(flat) == (0.0, 0.0, 7.0)
    assert is_uniform(flat)

    noisy = np.random.default_rng(1).integers(0, 255, (30, 30)).astype(np.uint8)
    assert not is_uniform(noisy)

    std, spread, mean = uniformity(np.zeros((0, 0), dtype=np.uint8))
    assert std == float("inf") and spread == float("inf") and mean == 0.0
    assert not is_uniform(np.zeros((0, 0), dtype=np.uint8))


def test_binarise_and_otsu():
    """Ink is dark. Otsu splits paper from toner; an explicit cut means black."""
    page = to_gray(synth.typed_page())
    threshold = otsu_threshold(page)
    assert 30 < threshold < 200
    assert 0.001 < binarise(page).mean() < 0.2  # a text page is mostly paper

    # Otsu has to follow the histogram it is given, not a remembered number:
    # the same document scanned dark and scanned light needs two answers.
    rng = np.random.default_rng(2)
    def bimodal(low, high):
        picks = rng.random((200, 200)) < 0.35
        values = np.where(picks, rng.normal(low, 3, (200, 200)), rng.normal(high, 3, (200, 200)))
        return np.clip(values, 0, 255).astype(np.uint8)

    assert otsu_threshold(bimodal(10, 60)) < 40 < otsu_threshold(bimodal(200, 240))

    assert binarise(np.full((4, 4), 200, np.uint8), 60).sum() == 0
    assert binarise(np.zeros((4, 4), np.uint8), 60).all()
    # A page of one flat colour has nothing to separate, so nothing is ink.
    assert not binarise(np.full((8, 8), 128, np.uint8)).any()


def test_to_gray_accepts_what_the_pipeline_actually_has():
    """PIL pages, numpy arrays, RGB and RGBA all reduce to one grey plane."""
    rgb = Image.new("RGB", (4, 4), (255, 0, 0))
    assert to_gray(rgb).shape == (4, 4)
    assert to_gray(rgb)[0, 0] == 76  # 0.299 * 255, Rec. 601
    assert to_gray(np.zeros((4, 4), np.uint8)).dtype == np.uint8
    assert to_gray(Image.new("RGBA", (4, 4), (0, 0, 0, 0)))[0, 0] == 0  # not composited
