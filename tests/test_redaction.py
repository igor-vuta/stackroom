def test_a_page_stamped_with_the_no_zorder_sentinel_has_no_draw_order(tmp_path):
    """``NO_ZORDER`` is *unknown*, and must never be read as a position.

    ``ingest/pdf.py`` stamps every shape on a page whose content stream it could
    not instrument with ``NO_ZORDER``, which is -1, and documents that callers
    must treat it as unknown and never as zero. This module used to test for a
    missing draw order by looking for ``seq is None`` - a value ``ingest/pdf.py``
    never emits - so on that whole degraded path the draw-order test silently
    answered "no" for every pair of shapes, and the warning written to catch
    exactly that never fired.

    The reproduction is the one from the review: a black box over ten glyphs,
    every ``seq`` -1, the characters a different ink from the box, so that
    colour matching cannot speak either. Before the fix this page came back
    ``hidden: []``, ``warnings: []`` - a clean bill of health for a page nobody
    had checked.
    """
    from stackroom.ingest.pdf import NO_ZORDER

    assert NO_ZORDER < 0, "the sentinel has to be outside the range of a real position"

    def page_with(seq_for_box: int, seq_for_char) -> RawPage:
        return RawPage(
            rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=seq_for_box)],
            chars=[
                Char(
                    text=ch,
                    x0=92 + i * 6,
                    top=602,
                    x1=98 + i * 6,
                    bottom=612.5,
                    seq=seq_for_char if isinstance(seq_for_char, int) else seq_for_char(i),
                    colour=(0.35, 0.35, 0.35),  # not the box's ink
                )
                for i, ch in enumerate("Anon Source")
            ],
        )

    # With real positions the page reports the hidden text: the box is painted
    # after the characters, which is the whole draw-order test.
    real = analyse_page(page_with(99, lambda i: 1 + i))
    assert [f.text for f in real.hidden] == ["Anon Source"]

    # With the sentinel we cannot say - and saying so is the point.
    sentinel = analyse_page(page_with(NO_ZORDER, NO_ZORDER))
    assert sentinel.hidden == []
    assert any("without a draw order" in w for w in sentinel.warnings), (
        "a page judged without a draw order has to say so"
    )


def test_a_sentinel_seq_is_never_compared_against_a_real_one():
    """Half a page of sentinels must not make the other half look painted-under.

    ``ingest/pdf.py`` decides per page, so today every shape on a page shares a
    fate. If that ever stops being true, ``-1 < 5`` must not be read as "this
    character was painted before that box": that is arithmetic on a value that
    means "we do not know".
    """
    page = RawPage(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=5)],
        chars=[
            Char(text=ch, x0=92 + i * 6, top=602, x1=98 + i * 6, bottom=612.5,
                 seq=-1, colour=(0.35, 0.35, 0.35))
            for i, ch in enumerate("Anon Source")
        ],
    )
    result = analyse_page(page)
    assert result.hidden == []
    assert any("without a draw order" in w for w in result.warnings)


def test_a_page_that_says_its_draw_order_is_unusable_is_believed():
    """``RawPage.has_zorder`` is honoured, and it used to be called from nowhere.

    The per-shape sentinel and the per-page flag are two independent ways of
    being told the same thing, and this module reads both: a caller whose
    sentinel is some other value still gets the honest answer.
    """

    @dataclass
    class Unordered:
        width: float = 612.0
        height: float = 792.0
        chars: list = field(default_factory=list)
        rects: list = field(default_factory=list)
        has_zorder: bool = False

    page = Unordered(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=99)],
        chars=[
            Char(text=ch, x0=92 + i * 6, top=602, x1=98 + i * 6, bottom=612.5,
                 seq=1 + i, colour=(0.35, 0.35, 0.35))
            for i, ch in enumerate("Anon Source")
        ],
    )
    result = analyse_page(page)
    assert result.hidden == [], "the positions are there but the page says not to trust them"
    assert any("without a draw order" in w for w in result.warnings)


def test_leak_stacked_boxes_are_two_redactions_not_one_span(tmp_path):
    """Two stacked boxes stay two boxes, and the gap between them stays visible.

    A multi-line redaction drawn as one path has an outer bounding box that
    covers the visible text between the lines. Anything that reads that bbox
    instead of the individual sub-rectangles reports text nobody hid, and an
    operator who is shown two false leaks stops reading the third.
    """
    page = RawPage(
        rects=[
            Rect(x0=90, top=600, x1=290, bottom=616, seq=100),
            Rect(x0=90, top=640, x1=290, bottom=656, seq=101),
        ],
        chars=(
            text_run("Hidden line one", x=92, top=602, seq=1)
            + text_run("PLAINLY VISIBLE", x=92, top=622, seq=40)  # in the gap
            + text_run("Hidden line two", x=92, top=642, seq=70)
        ),
    )
    findings = find_hidden_text(page, crop_renderer=flat_renderer())
    assert [f.text for f in findings] == ["Hidden line one", "Hidden line two"]
    assert all("VISIBLE" not in f.text for f in findings)

    result = analyse_page(page)
    assert len(result.redactions) == 2
    assert {round(r.box.h, 6) for r in result.redactions} == {round(16 / 792, 6)}


def test_leak_reported_even_when_the_box_carries_a_label(tmp_path):
    """A box that is not flat all over can still be hiding text.

    Real productions stamp "(b)(6)" or a white "REDACTED" onto the box. The
    rendering is then not uniform, so the box-level check cannot clear it - and
    the per-character check still can, because a glyph that is under the box
    has nothing but box colour in its own footprint.
    """
    page = RawPage(
        rects=[Rect(x0=90, top=600, x1=290, bottom=616, seq=100)],
        chars=text_run("Kept Underneath", x=92, top=602, seq=1),
    )

    def half_and_half(box: Box) -> Image.Image:
        # Flat black over the characters, a bright label in the right-hand
        # third, which is outside every character box in this page.
        img = Image.new("L", (200, 40), 0)
        ImageDraw.Draw(img).rectangle([170, 5, 195, 35], fill=255)
        return img

    assert [f.text for f in find_hidden_text(page, crop_renderer=half_and_half)] == [
        "Kept Underneath"
    ]


